"""Hold a real browser WebTransport stream through two Linux Helix execs.

Uses disposable loopback listeners, a private account store, a seven-day P-256
certificate, and the existing dependency-free Chromium harness. Requires Node,
Chromium and OpenSSL. No production service is contacted or signalled.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import os
from pathlib import Path
import secrets
import shutil
import signal
import socket
import ssl
import subprocess
import sys
import tempfile
import time

from windows_helix_smoke import Client
from windows_helix_tls_smoke import connect_tls, token
from windows_helix_webtransport_smoke import (
    held_control, require_held_identity, wait_held_status,
)
import windows_webtransport_smoke as wt

ROOT = Path(__file__).resolve().parent.parent


class FixtureFailure(Exception):
    """Only fixed, credential-free diagnostics generated by this fixture."""



def stop_group(process: subprocess.Popen | None) -> None:
    if process is None:
        return
    # Each fixture child gets its own process group, including browser children.
    try:
        os.killpg(process.pid, signal.SIGTERM)
    except ProcessLookupError:
        pass
    try:
        process.wait(timeout=5)
    except subprocess.TimeoutExpired:
        pass
    try:
        os.killpg(process.pid, signal.SIGKILL)
    except ProcessLookupError:
        pass
    process.wait(timeout=5)


def certificate(root: Path) -> str:
    subprocess.run([
        "openssl", "req", "-x509", "-newkey", "ec", "-pkeyopt",
        "ec_paramgen_curve:P-256", "-nodes", "-sha256", "-days", "7",
        "-subj", "/CN=localhost", "-addext", "subjectAltName=DNS:localhost,IP:127.0.0.1",
        "-keyout", str(root / "server.key"), "-out", str(root / "leaf.pem"),
    ], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=20)
    os.chmod(root / "server.key", 0o600)
    der = ssl.PEM_cert_to_DER_cert((root / "leaf.pem").read_text())
    return hashlib.sha256(der).hexdigest()


def wait_exec(process: subprocess.Popen, log: Path, previous: int) -> None:
    deadline = time.monotonic() + 30
    while time.monotonic() < deadline:
        if process.poll() is not None:
            raise FixtureFailure("fixture daemon exited during Helix")
        text = log.read_text(errors="replace")
        if text.count("Helix resume — adopting listen fd") > previous:
            return
        time.sleep(0.1)
    raise FixtureFailure("no successor exec/adoption observed; refusal is not a pass")


def run(binary_source: Path, successor: Path | None, browser: str, evidence: Path, rotate_certificate: bool) -> None:
    parent_dir = ROOT / ".upgrade-smoke"
    parent_dir.mkdir(mode=0o700, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="linux-wt-", dir=parent_dir) as temporary:
        root = Path(temporary)
        binary = root / "onyx-server"
        shutil.copy2(binary_source, binary)
        cert_hash = certificate(root)
        held_ports = [socket.socket() for _ in range(3)]
        udp = wt.udp_socket()
        try:
            for reservation in held_ports:
                reservation.bind(("127.0.0.1", 0))
            irc_port, tls_port, control_port = [s.getsockname()[1] for s in held_ports]
            wt_port = udp.getsockname()[1]
            config = root / "server.toml"
            config.write_text(
                f'[node]\nid = 1\nsecret_key = "{secrets.token_hex(32)}"\n'
                f'[cloak]\nsecret = "{secrets.token_hex(32)}"\n'
                '[limits]\nnum_shards = 2\n'
                f'[listen]\nhost = "127.0.0.1"\nirc = {irc_port}\nwebtransport = {wt_port}\n'
                f'[tls]\nenabled = true\nport = {tls_port}\ndns_name = "localhost"\n'
                'cert_path = "leaf.pem"\nkey_path = "server.key"\n'
                '[sasl]\nenabled = true\naccount_db = "accounts.wal"\n'
                '[accounts]\npbkdf2_rounds = 10000\n'
                # ONYX_SMOKE_PRESENCE=1 carries a durable mesh presence store.
                + ('[mesh]\npresence_store_path = "mesh-presence.wal"\n'
                   if os.environ.get("ONYX_SMOKE_PRESENCE") == "1" else '')
            )
            os.chmod(config, 0o600)
        finally:
            for reservation in held_ports:
                reservation.close()
            udp.close()

        context = ssl.SSLContext(ssl.PROTOCOL_TLS_CLIENT)
        context.check_hostname = False
        context.verify_mode = ssl.CERT_NONE  # Private fixture; browser pins DER hash.
        context.minimum_version = ssl.TLSVersion.TLSv1_3
        daemon = browser_process = None
        clients = []
        daemon_log = root / "daemon.log"
        browser_log = root / "browser.log"
        phase = "daemon startup"
        private_values: list[str] = []
        with daemon_log.open("wb") as output, browser_log.open("wb") as browser_output:
            try:
                daemon = subprocess.Popen([str(binary), str(config)], cwd=root,
                                          stdout=output, stderr=subprocess.STDOUT,
                                          start_new_session=True)
                owner = connect_tls(tls_port, context, daemon)
                clients.append(owner)
                owner.register(b"wtowner")
                password = secrets.token_urlsafe(24)
                private_values.append(password)
                owner.command(f"REGISTER wtaccount * {password}".encode(),
                              b"REGISTER SUCCESS", timeout=45)
                authenticated = connect_tls(tls_port, context, daemon)
                clients.append(authenticated)
                authenticated.command(b"CAP LS 302", b" LS ")
                authenticated.command(b"CAP REQ :sasl", b" ACK ")
                authenticated.command(b"AUTHENTICATE PLAIN", b"AUTHENTICATE +")
                proof = base64.b64encode(b"\0wtaccount\0" + password.encode())
                private_values.append(proof.decode())
                authenticated.command(b"AUTHENTICATE " + proof, b" 903 ", timeout=45)
                authenticated.send(b"CAP END")
                authenticated.register(b"wtaccount")
                original_token = token(authenticated)
                private_values.append(original_token.decode())
                observer = Client(irc_port)
                clients.append(observer)
                observer.register(b"wtobserver")
                observer.command(b"JOIN #web", b" 366 ")
                for index in range(8):
                    filler = Client(irc_port)
                    clients.append(filler)
                    filler.register(f"wtfill{index}".encode())

                phase = "browser baseline"
                browser_process = subprocess.Popen([
                    shutil.which("node"), str(wt.HARNESS), "--port", str(wt_port),
                    "--certhash", cert_hash, "--chromium", browser,
                    "--http-port", str(control_port), "--timeout-ms", "240000", "--held",
                ], cwd=root, env={**os.environ, "TMPDIR": str(root)},
                    stdout=browser_output, stderr=subprocess.STDOUT, start_new_session=True)
                ready = wait_held_status(browser_process, control_port, 0, browser_log)
                identity = ready.get("sessionId")
                if not isinstance(identity, str) or not identity:
                    raise FixtureFailure("browser omitted session identity")
                require_held_identity(ready, identity)
                observer.wait(b"PRIVMSG #web :wt-held-baseline", start=0)
                # Let QUIC handshake acknowledgement settle before the exact cut.
                print("PASS: real browser registered and joined; baseline channel delivery observed", flush=True)
                time.sleep(2)
                if rotate_certificate:
                    if certificate(root) == cert_hash:
                        raise FixtureFailure("certificate rotation did not change the fixture")
                    print("INFO: replaced on-disk certificate; held WebTransport must retain its source generation", flush=True)
                if successor is not None:
                    staged = root / "onyx-server.new"
                    shutil.copy2(successor, staged)
                    os.replace(staged, binary)

                messages = [b"wt-held-baseline"]
                for sequence in (1, 2):
                    phase = f"exec/adoption {sequence}"
                    before = daemon_log.read_text(errors="replace").count(
                        "Helix resume — adopting listen fd")
                    daemon.send_signal(signal.SIGUSR2)
                    wait_exec(daemon, daemon_log, before)
                    phase = f"held TCP/TLS continuity {sequence}"
                    marker = f"linux-wt-{sequence}".encode()
                    for client in clients:
                        client.ping(marker)
                    if token(authenticated) != original_token:
                        raise FixtureFailure("session token changed across actual Helix")
                    nonce = f"wt-held-{sequence}-{secrets.token_hex(4)}"
                    phase = f"held browser continuity {sequence}"
                    expected = {"phase": sequence, "nonce": nonce}
                    if held_control(control_port, "/probe", expected) != expected:
                        raise FixtureFailure("browser probe acknowledgement mismatch")
                    status = wait_held_status(browser_process, control_port, sequence, browser_log)
                    require_held_identity(status, identity)
                    if status.get("nonce") != nonce:
                        raise FixtureFailure("browser returned a stale probe")
                    messages.append(nonce.encode())
                    observer.wait(b"PRIVMSG #web :" + nonce.encode(), start=0)
                    observer.ping(b"delivery-cut-" + marker)
                    for message in messages:
                        if sum(line.startswith(b":webuser!") and
                               line.endswith(b"PRIVMSG #web :" + message)
                               for line in observer.lines) != 1:
                            raise FixtureFailure("WebTransport delivery missing or duplicated")
                    print(f"PASS: actual Linux Helix {sequence}; same PID, browser session/stream, "
                          "TLS token and held TCP clients; exact channel deliveries", flush=True)
                held_control(control_port, "/finish")
                if browser_process.wait(timeout=10) != 0:
                    raise FixtureFailure("browser fixture exited unsuccessfully")
                print("ALL CHECKS PASSED", flush=True)
            except Exception as error:
                if isinstance(error, FixtureFailure):
                    raise
                raise FixtureFailure(f"{phase}: {type(error).__name__}; see private evidence logs") from None
            finally:
                for client in clients:
                    client.close()
                stop_group(browser_process)
                stop_group(daemon)
                output.flush()
                browser_output.flush()
                for source in (daemon_log, browser_log):
                    contents = source.read_text(errors="replace")
                    for value in private_values:
                        contents = contents.replace(value, "[redacted]")
                    target = evidence / source.name
                    target.write_text(contents)
                    target.chmod(0o600)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("binary", type=Path)
    parser.add_argument("successor", type=Path, nargs="?")
    parser.add_argument("--chromium", default=shutil.which("chromium"))
    parser.add_argument("--rotate-certificate", action="store_true")
    parser.add_argument("--evidence-dir", type=Path,
                        help="new private directory for redacted daemon/browser logs")
    args = parser.parse_args()
    if not sys.platform.startswith("linux"):
        parser.error("requires Linux")
    if not args.chromium or not shutil.which("node") or not shutil.which("openssl"):
        parser.error("requires Chromium, Node.js and OpenSSL")
    try:
        evidence = args.evidence_dir or ROOT / ".release" / f"linux-wt-smoke-{os.getpid()}"
        evidence = evidence.resolve()
        evidence.mkdir(mode=0o700, parents=True, exist_ok=False)
        print(f"Evidence: {evidence}", flush=True)
        run(args.binary.resolve(strict=True),
            args.successor.resolve(strict=True) if args.successor else None,
            str(Path(args.chromium).resolve(strict=True)), evidence, args.rotate_certificate)
        return 0
    except Exception as error:
        # Helpers can include IRC lines in exceptions: never print credentials or tokens.
        detail = str(error) if isinstance(error, FixtureFailure) else type(error).__name__
        print(f"FAIL: Linux WebTransport Helix acceptance: {detail}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
