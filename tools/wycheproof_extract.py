"""Convert upstream Wycheproof JSON vectors into the compact line format that
src/crypto/wycheproof_kat.zig embeds with @embedFile.

Upstream: https://github.com/C2SP/wycheproof (testvectors_v1/), Apache-2.0.
The vendored files under src/crypto/testdata/wycheproof/ were produced from the
commit pinned in UPSTREAM_COMMIT below. To refresh:

    mkdir /tmp/wp && cd /tmp/wp
    for f in <names in FILES>; do
      curl -sSfO https://raw.githubusercontent.com/C2SP/wycheproof/<commit>/testvectors_v1/$f.json
    done
    python3 -I tools/wycheproof_extract.py /tmp/wp src/crypto/testdata/wycheproof

The conversion is lossless for every field the Zig drivers consume: hex fields
are copied verbatim (no normalization; the drivers do that), only presentation
fields (comments, PEM/JWK/DER duplicates of the same key) are dropped.

Line format (whitespace separated, one record per line, '#' starts a comment):
    G <group fields...>                      group parameters (per file, below)
    T <tcId> <v|i|a> <flags> <test fields...>
'v' = valid, 'i' = invalid, 'a' = acceptable. <flags> is a comma-joined list or
'-'. An empty hex field is written as '-'.
"""

import hashlib
import json
import os
import sys

UPSTREAM_COMMIT = "d17cc89fa5c8f4f4d378b5385ebf75da5d0926c9"

RESULT = {"valid": "v", "invalid": "i", "acceptable": "a"}


def h(s):
    return s if s else "-"


def aead(g, t):
    return (
        [str(g["keySize"]), str(g["ivSize"]), str(g["tagSize"])],
        [t["key"], t["iv"], t["aad"], t["msg"], t["ct"], t["tag"]],
    )


def dh(g, t):
    return None, [t["public"], t["private"], t["shared"]]


def ecdsa(g, t):
    return [g["publicKey"]["uncompressed"]], [t["msg"], t["sig"]]


def eddsa(g, t):
    return [g["publicKey"]["pk"]], [t["msg"], t["sig"]]


def rsa_pkcs1(g, t):
    assert g["sha"] == "SHA-256"
    pk = g["publicKey"]
    return [pk["modulus"], pk["publicExponent"]], [t["msg"], t["sig"]]


def rsa_pss(g, t):
    assert g["sha"] == "SHA-256" and g["mgf"] == "MGF1" and g["mgfSha"] == "SHA-256"
    pk = g["publicKey"]
    return [pk["modulus"], pk["publicExponent"], str(g["sLen"])], [t["msg"], t["sig"]]


def hkdf(g, t):
    return None, [t["ikm"], t["salt"], t["info"], str(t["size"]), t["okm"]]


# name -> (converter, documentation of the G / T trailing fields)
FILES = {
    "aes_gcm_test": (aead, "G keyBits ivBits tagBits | T key iv aad msg ct tag"),
    "chacha20_poly1305_test": (aead, "G keyBits ivBits tagBits | T key iv aad msg ct tag"),
    "x25519_test": (dh, "T public private shared"),
    "ecdh_secp256r1_ecpoint_test": (dh, "T public(SEC1) private(int) shared"),
    "ecdsa_secp256r1_sha256_test": (ecdsa, "G pubSec1Uncompressed | T msg sigDer"),
    "ecdsa_secp256r1_sha256_p1363_test": (ecdsa, "G pubSec1Uncompressed | T msg sigP1363"),
    "ed25519_test": (eddsa, "G pk | T msg sig"),
    "rsa_signature_2048_sha256_test": (rsa_pkcs1, "G n e | T msg sig"),
    "rsa_pss_2048_sha256_mgf1_0_test": (rsa_pss, "G n e sLen | T msg sig"),
    "rsa_pss_2048_sha256_mgf1_32_test": (rsa_pss, "G n e sLen | T msg sig"),
    "hkdf_sha256_test": (hkdf, "T ikm salt info size okm"),
}


def convert(src_dir, out_dir, name):
    conv, layout = FILES[name]
    path = os.path.join(src_dir, name + ".json")
    raw = open(path, "rb").read()
    doc = json.loads(raw)
    lines = [
        "# Wycheproof %s (%s)" % (name, doc["algorithm"]),
        "# upstream: github.com/C2SP/wycheproof@%s testvectors_v1/%s.json" % (UPSTREAM_COMMIT, name),
        "# upstream sha256: %s" % hashlib.sha256(raw).hexdigest(),
        "# license: Apache-2.0; generated by tools/wycheproof_extract.py",
        "# layout: %s" % layout,
        "# tests: %d" % doc["numberOfTests"],
    ]
    count = 0
    for g in doc["testGroups"]:
        first = True
        for t in g["tests"]:
            gfields, tfields = conv(g, t)
            if first and gfields is not None:
                lines.append("G " + " ".join(h(x) for x in gfields))
            first = False
            flags = ",".join(t["flags"]) if t["flags"] else "-"
            lines.append(
                "T %d %s %s %s"
                % (t["tcId"], RESULT[t["result"]], flags, " ".join(h(x) for x in tfields))
            )
            count += 1
    assert count == doc["numberOfTests"], (name, count, doc["numberOfTests"])
    with open(os.path.join(out_dir, name + ".txt"), "w") as out:
        out.write("\n".join(lines) + "\n")
    return count


def main():
    if len(sys.argv) != 3:
        sys.exit("usage: wycheproof_extract.py <json-dir> <out-dir>")
    src_dir, out_dir = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    for name in FILES:
        print("%-40s %d" % (name, convert(src_dir, out_dir, name)))


if __name__ == "__main__":
    main()
