const testing = std.testing;

/// Test host context: stands in for `*LinuxServer` as the erased ctx.
const FakeHost = struct {
    conns: i128 = 0,
    peers: i128 = 0,

    fn readConns(ctx: *anyopaque) i128 {
        const self: *FakeHost = @ptrCast(@alignCast(ctx));
        return self.conns;
    }

    fn readPeers(ctx: *anyopaque) i128 {
        const self: *FakeHost = @ptrCast(@alignCast(ctx));
        return self.peers;
    }
};

const fake_entries = [_]Entry{
    .{ .module_id = "core.test", .spec = .{
        .prom = "onyx_test_conns",
        .irc = "t_conns",
        .help = "Test connections",
        .kind = .gauge,
        .category = .conn,
        .read = FakeHost.readConns,
    } },
    .{ .module_id = "mesh.test", .spec = .{
        .prom = "onyx_test_peers",
        .irc = "t_peers",
        .help = "Test peers",
        .kind = .counter,
        .category = .mesh,
        .read = FakeHost.readPeers,
    } },
};

const Collector = struct {
    lines: std.ArrayList([]const u8) = .empty,
    allocator: std.mem.Allocator,

    fn emit(self: *@This(), line: []const u8) anyerror!void {
        // The renderer reuses one stack buffer per iteration, so a collector
        // MUST copy: retaining `line` would dangle on the next iteration.
        try self.lines.append(self.allocator, try self.allocator.dupe(u8, line));
    }

    fn deinit(self: *@This()) void {
        for (self.lines.items) |l| self.allocator.free(l);
        self.lines.deinit(self.allocator);
    }
};

test "human rendering emits one token line per provider, reading live values" {
    var host = FakeHost{ .conns = 7, .peers = 3 };
    var c = Collector{ .allocator = testing.allocator };
    defer c.deinit();

    try forEachHuman(&fake_entries, &host, null, &c, Collector.emit);

    try testing.expectEqual(@as(usize, 2), c.lines.items.len);
    try testing.expectEqualStrings("t_conns = 7", c.lines.items[0]);
    try testing.expectEqualStrings("t_peers = 3", c.lines.items[1]);
}

test "providers are pull-based: a later mutation is reflected on the next render" {
    var host = FakeHost{ .conns = 1 };
    var first = Collector{ .allocator = testing.allocator };
    defer first.deinit();
    try forEachHuman(fake_entries[0..1], &host, null, &first, Collector.emit);
    try testing.expectEqualStrings("t_conns = 1", first.lines.items[0]);

    host.conns = 42;
    var second = Collector{ .allocator = testing.allocator };
    defer second.deinit();
    try forEachHuman(fake_entries[0..1], &host, null, &second, Collector.emit);
    try testing.expectEqualStrings("t_conns = 42", second.lines.items[0]);
}

test "category filter narrows the dump to one subsystem" {
    var host = FakeHost{ .conns = 7, .peers = 3 };
    var c = Collector{ .allocator = testing.allocator };
    defer c.deinit();

    try forEachHuman(&fake_entries, &host, .mesh, &c, Collector.emit);

    try testing.expectEqual(@as(usize, 1), c.lines.items.len);
    try testing.expectEqualStrings("t_peers = 3", c.lines.items[0]);
}

test "structured rendering is Prometheus sample syntax with module and kind labels" {
    var host = FakeHost{ .conns = 7, .peers = 3 };
    var c = Collector{ .allocator = testing.allocator };
    defer c.deinit();

    try forEachStructured(&fake_entries, &host, null, &c, Collector.emit);

    try testing.expectEqualStrings(
        "onyx_test_conns{module=\"core.test\",category=\"conn\",kind=\"gauge\"} 7",
        c.lines.items[0],
    );
    try testing.expectEqualStrings(
        "onyx_test_peers{module=\"mesh.test\",category=\"mesh\",kind=\"counter\"} 3",
        c.lines.items[1],
    );
}

test "prometheus export carries HELP, TYPE, and the sample" {
    var host = FakeHost{ .conns = 5, .peers = 9 };
    var out: std.ArrayList(u8) = .empty;
    defer out.deinit(testing.allocator);

    try writePrometheus(&fake_entries, &host, testing.allocator, &out);

    try testing.expect(std.mem.indexOf(u8, out.items, "# HELP onyx_test_conns Test connections") != null);
    try testing.expect(std.mem.indexOf(u8, out.items, "# TYPE onyx_test_conns gauge") != null);
    try testing.expect(std.mem.indexOf(u8, out.items, "onyx_test_conns 5") != null);
    try testing.expect(std.mem.indexOf(u8, out.items, "# TYPE onyx_test_peers counter") != null);
    try testing.expect(std.mem.indexOf(u8, out.items, "onyx_test_peers 9") != null);
}

test "negative gauge values render signed, not wrapped" {
    const Neg = struct {
        fn read(_: *anyopaque) i128 {
            return -5;
        }
    };
    const entries = [_]Entry{.{ .module_id = "m", .spec = .{
        .prom = "onyx_neg",
        .irc = "neg",
        .help = "h",
        .kind = .gauge,
        .read = Neg.read,
    } }};
    var host = FakeHost{};
    var c = Collector{ .allocator = testing.allocator };
    defer c.deinit();
    try forEachHuman(&entries, &host, null, &c, Collector.emit);
    try testing.expectEqualStrings("neg = -5", c.lines.items[0]);
}

test "prometheus and irc name validators accept legal names and reject malformed ones" {
    try testing.expect(validPromName("onyx_conns_total"));
    try testing.expect(validPromName("_leading_underscore"));
    try testing.expect(validPromName("ns:metric"));
    try testing.expect(!validPromName(""));
    try testing.expect(!validPromName("0starts_with_digit"));
    try testing.expect(!validPromName("has space"));
    try testing.expect(!validPromName("has-dash"));
    try testing.expect(!validPromName("has\"quote"));
    try testing.expect(!validPromName("has{brace"));
    try testing.expect(!validPromName("has\nnewline"));

    try testing.expect(validIrcToken("conns_active"));
    try testing.expect(!validIrcToken(""));
    try testing.expect(!validIrcToken("has space"));
    // A colon is legal in Prometheus but not in the `token = value` oper dump.
    try testing.expect(!validIrcToken("ns:metric"));
}

test "category token resolution is case-insensitive and fails closed on garbage" {
    try testing.expectEqual(Category.mesh, categoryFromToken("mesh").?);
    try testing.expectEqual(Category.mesh, categoryFromToken("MESH").?);
    try testing.expectEqual(Category.reactor, categoryFromToken("Reactor").?);
    try testing.expect(categoryFromToken("nosuchcategory") == null);
    try testing.expect(categoryFromToken("") == null);
}

test "an over-long provider line is skipped rather than truncated" {
    const Big = struct {
        fn read(_: *anyopaque) i128 {
            return 1;
        }
    };
    // An irc token longer than the render buffer cannot produce a valid line.
    const token_buf: [max_line_len + 8]u8 = @splat('x');
    const entries = [_]Entry{
        .{ .module_id = "m", .spec = .{
            .prom = "onyx_ok",
            .irc = "ok",
            .help = "h",
            .read = Big.read,
        } },
        .{ .module_id = "m", .spec = .{
            .prom = "onyx_too_long",
            .irc = &token_buf,
            .help = "h",
            .read = Big.read,
        } },
    };
    var host = FakeHost{};
    var c = Collector{ .allocator = testing.allocator };
    defer c.deinit();
    try forEachHuman(&entries, &host, null, &c, Collector.emit);
    // Only the well-formed provider rendered; the oversized one was dropped.
    try testing.expectEqual(@as(usize, 1), c.lines.items.len);
    try testing.expectEqualStrings("ok = 1", c.lines.items[0]);
}
