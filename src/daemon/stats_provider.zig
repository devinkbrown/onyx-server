//! Module-facing stats provider interface — how a SerpentRegistry module
//! contributes a counter or gauge to `/STATS` and to the Prometheus endpoint.
//!
//! Before this existed, every exported metric had to be a hand-written field on
//! `server_stats.Stats` plus a hand-written row in its fixed `rows()` array, so
//! a module could not export anything. A module now declares
//! `stats: []const stats_provider.Spec` and the comptime registry aggregates
//! every module's providers into one flat table (`Live.stats`).
//!
//! Three renderings share that one table so they can never disagree:
//!
//!   * `forEachHuman`      — `conns_active = 5`, the oper `STATS z`/`STATS x` dump.
//!   * `forEachStructured` — `onyx_conns_active{module="core",category="conn",
//!                            kind="gauge"} 5`, machine-readable for scripts.
//!   * `writePrometheus`   — HELP/TYPE/sample exposition text.
//!
//! Reading is pull-based and allocation-free: a provider is a pure function of
//! the host context, called only on the cold render path. The hot path keeps
//! bumping its own atomics (see `server_stats.zig`); a provider just exposes one.
//!
//! Names are validated at COMPILE TIME (see `registry.validate`): a metric name
//! that is not a legal Prometheus identifier, or that collides with another
//! module's, is a build failure — never a corrupt scrape at runtime.
const std = @import("std");

/// Metric semantics. A `counter` only ever increases; a `gauge` moves both ways.
pub const Kind = enum {
    counter,
    gauge,

    pub fn token(self: Kind) []const u8 {
        return @tagName(self);
    }
};

/// Coarse subsystem grouping, so an operator can ask for one slice of the
/// metric surface (`STATS x mesh`) instead of the whole dump.
pub const Category = enum {
    conn,
    traffic,
    reactor,
    tls,
    mesh,
    media,
    security,
    world,
    module,

    pub fn token(self: Category) []const u8 {
        return @tagName(self);
    }
};

/// Provider read function. `ctx` is the erased host context the daemon passes to
/// every module entry point (`*server.LinuxServer` in the live server, exactly
/// like a command handler's or lifecycle fn's ctx). A provider MUST NOT mutate
/// through it, MUST NOT allocate, and MUST NOT block: it runs on the reactor
/// thread that is answering the operator's `STATS`.
///
/// `i128` is wide enough to hold both a `u64` monotonic counter and an `i64`
/// signed gauge without either saturating or wrapping.
pub const ReadFn = *const fn (ctx: *anyopaque) i128;

/// One metric declared by a module.
pub const Spec = struct {
    /// Prometheus metric name. Unique across all modules; must match
    /// `[a-zA-Z_:][a-zA-Z0-9_:]*` (enforced at comptime by `registry.validate`).
    prom: []const u8,
    /// Short token used in the oper `STATS` dump. Unique across all modules;
    /// must match `[a-zA-Z_][a-zA-Z0-9_]*`.
    irc: []const u8,
    /// One-line HELP text for the Prometheus exposition and `STATSPROVIDERS`.
    help: []const u8,
    kind: Kind = .counter,
    category: Category = .module,
    read: ReadFn,
};

/// Immutable stats-table row generated by `registry.Registry`.
pub const Entry = struct {
    module_id: []const u8,
    spec: Spec,
};

/// Longest single rendered line any renderer here emits. The longest form is the
/// structured one: name + module + category + kind labels + a signed 128-bit
/// decimal value. Providers whose rendering would exceed this are skipped rather
/// than truncated (a half-written metric is worse than an absent one).
pub const max_line_len = 512;

/// Whether `name` is a legal Prometheus metric name: `[a-zA-Z_:][a-zA-Z0-9_:]*`.
/// Rejecting at comptime keeps a malformed name from silently corrupting the
/// exposition format (a scrape parse error takes out every metric, not one).
pub fn validPromName(name: []const u8) bool {
    if (name.len == 0) return false;
    for (name, 0..) |c, i| {
        const alpha = (c >= 'a' and c <= 'z') or (c >= 'A' and c <= 'Z') or c == '_' or c == ':';
        const digit = c >= '0' and c <= '9';
        if (i == 0) {
            if (!alpha) return false;
        } else if (!alpha and !digit) return false;
    }
    return true;
}

/// Whether `token` is a legal short `STATS` token: `[a-zA-Z_][a-zA-Z0-9_]*`.
/// Stricter than `validPromName` (no `:`) because the oper dump renders
/// `token = value` and a colon reads as a namespace separator to scripts.
pub fn validIrcToken(token: []const u8) bool {
    if (token.len == 0) return false;
    for (token, 0..) |c, i| {
        const alpha = (c >= 'a' and c <= 'z') or (c >= 'A' and c <= 'Z') or c == '_';
        const digit = c >= '0' and c <= '9';
        if (i == 0) {
            if (!alpha) return false;
        } else if (!alpha and !digit) return false;
    }
    return true;
}

/// Emit `irc = value` per provider through `emit`. Never allocates; formats into
/// a stack buffer. `filter` narrows to one category (`null` = every category).
///
/// A provider whose line would overflow `max_line_len` is skipped, not
/// truncated. Renderer errors from `emit` propagate (the caller's send queue
/// filling up must not be swallowed).
pub fn forEachHuman(
    entries: []const Entry,
    ctx: *anyopaque,
    filter: ?Category,
    sink: anytype,
    comptime emit: fn (@TypeOf(sink), []const u8) anyerror!void,
) !void {
    var buf: [max_line_len]u8 = undefined;
    for (entries) |entry| {
        if (filter) |want| {
            if (entry.spec.category != want) continue;
        }
        const value = entry.spec.read(ctx);
        const line = std.fmt.bufPrint(&buf, "{s} = {d}", .{ entry.spec.irc, value }) catch continue;
        try emit(sink, line);
    }
}

/// Emit one machine-readable line per provider through `emit`, in Prometheus
/// sample syntax so a script can parse `/STATS` output with the same code it
/// uses on the metrics endpoint:
///
///     onyx_conns_active{module="core",category="conn",kind="gauge"} 5
///
/// Never allocates. `filter` narrows to one category (`null` = every category).
pub fn forEachStructured(
    entries: []const Entry,
    ctx: *anyopaque,
    filter: ?Category,
    sink: anytype,
    comptime emit: fn (@TypeOf(sink), []const u8) anyerror!void,
) !void {
    var buf: [max_line_len]u8 = undefined;
    for (entries) |entry| {
        if (filter) |want| {
            if (entry.spec.category != want) continue;
        }
        const value = entry.spec.read(ctx);
        const line = std.fmt.bufPrint(&buf, "{s}{{module=\"{s}\",category=\"{s}\",kind=\"{s}\"}} {d}", .{
            entry.spec.prom,
            entry.module_id,
            entry.spec.category.token(),
            entry.spec.kind.token(),
            value,
        }) catch continue;
        try emit(sink, line);
    }
}

/// Append Prometheus exposition text (HELP/TYPE/sample per provider) to `out`.
/// Mirrors `server_stats.Stats.writePrometheus` so module-contributed metrics
/// are indistinguishable from the built-in ones to a scraper.
pub fn writePrometheus(
    entries: []const Entry,
    ctx: *anyopaque,
    allocator: std.mem.Allocator,
    out: *std.ArrayList(u8),
) !void {
    for (entries) |entry| {
        try out.print(allocator, "# HELP {s} {s}\n", .{ entry.spec.prom, entry.spec.help });
        try out.print(allocator, "# TYPE {s} {s}\n", .{ entry.spec.prom, entry.spec.kind.token() });
        try out.print(allocator, "{s} {d}\n", .{ entry.spec.prom, entry.spec.read(ctx) });
    }
}

/// Resolve a category token (`"mesh"`, case-insensitive) to a `Category`.
/// Returns null for an unknown token so the caller can fail closed with a usage
/// reply instead of silently dumping everything.
pub fn categoryFromToken(token: []const u8) ?Category {
    inline for (@typeInfo(Category).@"enum".field_names) |name| {
        if (std.ascii.eqlIgnoreCase(name, token)) return @field(Category, name);
    }
    return null;
}

